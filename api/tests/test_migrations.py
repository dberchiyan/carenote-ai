"""The migrations and the models describe the same schema."""

from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import Engine

from tests.conftest import API_DIR, OWNER_URL


def test_models_match_the_migrated_schema(owner_engine: Engine) -> None:
    """`alembic check`: a model change without a migration (or the reverse) fails here, not
    in production. The test database is at head already (session fixture)."""
    cfg = Config(str(API_DIR / "alembic.ini"))
    cfg.set_main_option("script_location", str(API_DIR / "migrations"))
    cfg.set_main_option("sqlalchemy.url", OWNER_URL)
    cfg.attributes["skip_url_from_settings"] = True
    try:
        command.check(cfg)
    except AutogenerateDiffsDetected as exc:
        raise AssertionError(f"models and migrations differ: {exc}") from exc
