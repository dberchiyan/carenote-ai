def build() -> list[dict[str, Any]]:
    ids = {p.full_name: str(p.id) for p in generate_patients()}
    rows = []
    for i, spec in enumerate(SPECS, start=1):
        tags, difficulty, ward, text, patient, candidates, vitals, symptoms, meds, uncertain = spec
        rows.append(
            {
                "id": f"holdout-{i:03d}",
                "tags": tags,
                "difficulty": difficulty,
                "ward": ward,
                "text": text,
                "expected_patient_id": ids[patient] if patient else None,
                "expected_patient_candidates": [
                    ids[n] for n in (candidates or ([patient] if patient else []))
                ],
                "expected_vitals": [
                    {"kind": k, "value": float(v), "unit": UCUM[k]} for k, v in vitals.items()
                ],
                "expected_symptoms": symptoms,
                "expected_medications": [{"name": n, "dose": d, "route": r} for n, d, r in meds],
                "expected_uncertain_kinds": uncertain,
                "notes": [],
                "audio_file": f"audio/holdout-{i:03d}.wav",
            }
        )
    return rows


def main() -> None:
    rows = build()
    OUT.write_text("".join(json.dumps(r, sort_keys=True) + "\n" for r in rows))
    print(f"Wrote {len(rows)} held-out cases to {OUT}")


if __name__ == "__main__":
    main()
